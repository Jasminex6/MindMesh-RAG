            '        scores = np.dot(self.doc_vectors, q_vec)\n',
            '        top_idx = np.argsort(scores)[::-1][:top_k]\n',
            '        return [{"score": float(scores[i]), "chunk": self.chunks[i]} for i in top_idx]\n',
