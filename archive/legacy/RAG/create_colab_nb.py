            '    def _tok(self, text):\n',
            '        return re.findall(r"\\b\\w+\\b", text.lower())\n',
            '\n',
            '    def _build(self):\n',
            '        words = set()\n',
            '        doc_toks = []\n',
            '        for c in self.chunks:\n',
            '            t = self._tok(c["text"])\n',
            '            doc_toks.append(t)\n',
            '            words.update(t)\n',
            '        self.vocab = {w: i for i, w in enumerate(sorted(words))}\n',
            '        for t in doc_toks:\n',
            '            vec = np.zeros(len(self.vocab), dtype=np.float32)\n',
            '            for w in t:\n',
            '                if w in self.vocab:\n',
            '                    vec[self.vocab[w]] += 1.0\n',
            '            n = np.linalg.norm(vec)\n',
            '            if n > 0:\n',
            '                vec /= n\n',
            '            self.doc_vectors.append(vec)\n',
            '        self.doc_vectors = np.array(self.doc_vectors)\n',
            '\n',
            '    def search(self, query, top_k=2):\n',
